with TRIPS as (

select
RIDEID,
--RIDEABLETYPE,
DATE(TO_TIMESTAMP(STARTEDAT)) AS TRIP_DATE,
STARTSTATIONID as START_STATION_ID,
ENDSTATIONID as END_STATION_ID,
MEMBERCASUALRIDE as MEMBER_CASUAL,
TIMESTAMPDIFF(SECOND, TO_TIMESTAMP(STARTEDAT), TO_TIMESTAMP(ENDEDAT)) AS TRIP_DURATION_SECONDS


from {{ref('stg_bike')}}

where RIDEID != 'ride_id'


limit 10

)

select 
*
from TRIPS 