WITH CTE AS (

select 

TO_TIMESTAMP(STARTEDAT) AS STARTEDAT,
DATE(TO_TIMESTAMP(STARTEDAT)) AS DATE_STARTEDAT,
HOUR(TO_TIMESTAMP(STARTEDAT)) AS HOUR_STARTEDAT,
CASE 
WHEN DAYNAME(TO_TIMESTAMP(STARTEDAT)) in ('Sat','Sun')
THEN 'WEEKEND'
ELSE 'BUSINESSDAY'
END AS DAY_TYPE,

CASE WHEN MONTH(TO_TIMESTAMP(STARTEDAT)) in (12,1,2)
THEN 'WINTER'
WHEN MONTH(TO_TIMESTAMP(STARTEDAT)) in (3,4,5)
THEN 'SPRING'
WHEN MONTH(TO_TIMESTAMP(STARTEDAT)) in (6,7,8)
THEN 'SUMMER'
WHEN MONTH(TO_TIMESTAMP(STARTEDAT)) in (9,10,11)
THEN 'AUTUMN'
END AS STATION_OF_YEAR


from 
{{source('demo', 'bike') }}

)

select 
*
from CTE


